#!/usr/bin/env python3
"""Generate a faithful local (WSL) build script from the CI workflow's build job.

Instead of hand-copying ~1500 lines of shell (error-prone), parse the YAML and
emit the same run blocks in the same order, with CI-only variables replaced by
local equivalents and CI-only steps (artifacts/releases/upload) skipped.
"""
import sys
import yaml

WF = ".github/workflows/build-sk-d840n.yml"
BASE = "/home/opc/skbuild"
REPO = BASE + "/repo"
MODE = "flash"  # user wants a flashable sysupgrade image

# Steps to skip: CI plumbing, diagnostics-on-failure, artifact/release upload,
# and things needing GitHub runner environment (rustup toolchain install is kept
# but made optional).
SKIP_EXACT = {
    "Skip by input mode",
    "Free disk space",
    "Init build environment",          # deps already installed manually in WSL
    "Clone sources",                   # already cloned manually into /home/opc/skbuild
    "Rust 1.96.1 and offline ONU regression tests",  # gate test, not build
    "Prepare firmware tools and upgrade regression tests",  # gate test, not build
    "What the build was done when it stopped",
    "What the build was doing when it stopped",
    "Upload logs on failure",
    "Upload outputs",
    "Upload direct sysupgrade image",
    "Publish release",
    "Direct firmware download summary",
    "Checksums and summary",
    "Bootweb download summary",
    "Stage trial inputs",  # initramfs-only scaffolding
    "Package initramfs image",  # only need flash sysupgrade
    # All CI quality gates are skipped: they validate code, not produce firmware.
    'Gate: declared LED topology and software negative controls',
    'Gate: every header the 9132 driver includes exists',
    'Gate: the macro gate is right about macros and enum members',
    'Gate: every macro the 9132 driver uses is reachable',
    'Gate: actual kernel and modules have the requested version',
    'Gate: ONU UI, protocol service and firewall4 reached the image',
    'Gate: the recovery service reached the image',
    'Gate: every dtb compatible has a driver in this kernel',
}
# Gate steps whose name uses double quotes in YAML are normalized by yaml.safe_load
SKIP_PREFIX = ("Gate:",)

with open(WF, encoding="utf-8") as f:
    doc = yaml.safe_load(f)

build = doc["jobs"]["build"]
env_globals = doc.get("env", {}) or {}
steps = build["steps"]

out = []
out.append("#!/bin/bash")
out.append("# AUTO-GENERATED by tools/gen_local_build.py -- do not edit by hand.")
out.append("set -o pipefail")
out.append(f"export GITHUB_WORKSPACE={REPO}")
for k, v in env_globals.items():
    if isinstance(v, str) and "${{" not in v:
        out.append(f"export {k}='{v}'")
out.append("export CCACHE_DIR=/home/opc/.cache/ccache")
out.append("export CCACHE_MAXSIZE=2G")
out.append("export KVER=6.18.60")
out.append("export SKD840N_HOST_PYTHON=$(command -v python3)")
out.append(f"export ZX_CARGO=$(command -v cargo || true)")
out.append("export GIT_HTTP_LOW_SPEED_LIMIT=1000 GIT_HTTP_LOW_SPEED_TIME=60 GIT_TERMINAL_PROMPT=0")
out.append("export CURL_OPTIONS='--speed-limit 100 --speed-time 120'")
out.append("export WGET_OPTIONS='--read-timeout=120 --timeout=120'")
out.append(f"export MODE={MODE}")
out.append(f'echo "LOCAL BUILD START $(date) mode={MODE}"')
out.append("")
# Pin the manually-cloned source trees to the exact SHAs CI uses (from Clone sources step).
# Source trees live under the workspace root, exactly like CI ($GITHUB_WORKSPACE/openwrt).
out.append("echo '========== PIN SOURCE TREES =========='")
out.append(f"cd {REPO} || exit 90")
out.append("git -C openwrt fetch --depth 1 origin \"$IW_SHA\" && git -C openwrt checkout --detach \"$IW_SHA\" || true")
out.append('test "$(git -C openwrt rev-parse HEAD)" = "$IW_SHA" || { echo "openwrt SHA mismatch"; exit 91; }')
out.append('KT="$KERNEL_SOURCE_DIR"')
out.append('git -C "$KT" checkout --detach "$KERNEL_SHA"')
out.append('git -C "$KT" submodule update --init --recursive')
out.append('test "$(git -C "$KT" rev-parse HEAD)" = "$KERNEL_SHA" || { echo "kernel SHA mismatch"; exit 92; }')
out.append('echo "Pinned kernel: $(git -C "$KT" rev-parse HEAD)"')
out.append("")

cur_wd = None
for idx, step in enumerate(steps):
    name = str(step.get("name", f"step{idx}")).strip()
    run = step.get("run")
    wd = step.get("working-directory")
    if not run:
        continue
    if name in SKIP_EXACT or name.startswith(SKIP_PREFIX):
        out.append(f"echo '[SKIP] {name}'")
        continue
    # replace GitHub expressions / runner vars
    script = run
    script = script.replace("${{ matrix.mode }}", MODE)
    script = script.replace("${{ github.workspace }}", REPO)
    script = script.replace("$GITHUB_WORKSPACE", REPO)
    script = script.replace("$RUNNER_TEMP", "/tmp")
    script = script.replace("$GITHUB_ENV", "/home/opc/.gh_env")
    script = script.replace("$GITHUB_OUTPUT", "/home/opc/.gh_out")
    script = script.replace("$KERNEL_SOURCE_DIR", str(env_globals.get("KERNEL_SOURCE_DIR", "linux-mainline-zte-zxslc-sr1010/linux-6.18.38")))
    script = script.replace("$GITHUB_STEP_SUMMARY", "/home/opc/.gh_summary")
    # drop lines that are pure GitHub workflow commands
    kept = []
    for line in script.split("\n"):
        s = line.strip()
        if s.startswith("echo ") and (">> \"$GITHUB" in line or ">> $GITHUB" in line or ">> \"/home/opc/.gh" in line):
            continue
        # neutralize workflow commands so they are harmless plain text locally
        line = line.replace("::error::", "ERROR: ")
        line = line.replace("::warning::", "WARN: ")
        line = line.replace("::notice::", "NOTE: ")
        kept.append(line)
    script = "\n".join(kept)

    # working directory handling
    target_wd = REPO
    if wd:
        if wd == "openwrt":
            target_wd = REPO + "/openwrt"
        else:
            target_wd = REPO + "/" + wd
    out.append(f'echo "========== STEP {idx}: {name} =========="')
    out.append(f"cd {target_wd} || {{ echo 'CD FAILED {target_wd}'; exit 90; }}")
    out.append("(")
    out.append(script)
    out.append(")")
    out.append(f"rc=$?; if [ $rc -ne 0 ]; then echo 'STEP FAILED: {name} (rc='$rc')'; exit $rc; fi")
    out.append("")

out.append('echo "LOCAL BUILD ALL STEPS DONE $(date)"')
sys.stdout.write("\n".join(out) + "\n")
